/* Builds js/placement-pool.js from js/puzzles.js.
 *
 * Every puzzle in the bank is a legal position with a forced mate. The winning
 * moves come from the same search the test itself judges with
 * (Placement.correctMoves), so the generator and the board can never disagree
 * about what counts as a mate. The pool is written out as data, and
 * tools/check-placement.js re-verifies all of it afterwards.
 *
 *   node tools/make-placement.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const Engine = require(path.join(__dirname, '..', 'js', 'engine.js'));
const Placement = require(path.join(__dirname, '..', 'js', 'placement.js'));

const root = path.join(__dirname, '..');
const puzzleSource = fs.readFileSync(path.join(root, 'js', 'puzzles.js'), 'utf8');
const sandbox = {};
new Function('window', puzzleSource)(sandbox);
const PUZZLES = sandbox.PUZZLES;

function winningMoves(fen, mateIn) {
  const game = new Engine.Chess(fen);
  return Placement.correctMoves(game, { kind: 'mate', mateIn: mateIn });
}

const pool = [];

PUZZLES.forEach((puzzle, index) => {
  const game = new Engine.Chess(puzzle.fen);
  const legal = game.legalMoves();
  const answers = winningMoves(puzzle.fen, puzzle.mateIn);
  if (!answers.length) {
    console.error('# puzzle ' + index + ' has no usable answer — skipped');
    return;
  }

  const answer = answers[0];
  const san = game.san(answer, legal);
  /* spread the ladder ratings so mate-in-1 sits below mate-in-2 */
  const rating = puzzle.mateIn === 1
    ? 1000 + (index % 7) * 45
    : 1480 + (index % 7) * 45;

  pool.push({
    id: 'puzzle-' + index,
    kind: 'mate',
    mateIn: puzzle.mateIn,
    rating: rating,
    fen: puzzle.fen,
    answer: Engine.moveToUci(answer),
    prompt: puzzle.mateIn === 1 ? 'White to move. Mate in one.' : 'White to move. Mate in two.',
    why: puzzle.mateIn === 1
      ? san + ' is mate \u2014 the king has no escape square.'
      : san + ' forces mate \u2014 every reply runs into a mating move.'
  });
});

pool.sort((a, b) => a.rating - b.rating);

function entry(q) {
  return "    { id: '" + q.id + "', kind: 'mate', mateIn: " + q.mateIn + ", rating: " + q.rating + ',\n' +
    "      fen: '" + q.fen + "', answer: '" + q.answer + "',\n" +
    "      prompt: '" + q.prompt + "',\n" +
    "      why: '" + q.why.replace(/'/g, "\\'") + "' }";
}

const file = '/* Generated by tools/make-placement.js from js/puzzles.js \u2014 do not edit by hand. */\n' +
  '(function (global) {\n' +
  "  'use strict';\n\n" +
  '  var POOL = [\n' +
  pool.map(entry).join(',\n') + '\n' +
  '  ];\n\n' +
  '  global.PLACEMENT_POOL = POOL;\n' +
  "  if (typeof module === 'object' && module.exports) module.exports = POOL;\n" +
  "})(typeof self !== 'undefined' ? self : globalThis);\n";

fs.writeFileSync(path.join(root, 'js', 'placement-pool.js'), file);
console.log('wrote js/placement-pool.js with ' + pool.length + ' positions');
console.log('ratings ' + pool[0].rating + '..' + pool[pool.length - 1].rating);
